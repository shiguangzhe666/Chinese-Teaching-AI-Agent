def get_interaction_prompt(grade, lesson):
    """课堂互动模拟提示词"""
    return f"""请为统编版{grade}《{lesson}》设计课堂师生互动模拟，包含以下内容：

## 一、课堂导入话术
设计2-3种不同风格的导入话术（情境导入/问题导入/故事导入等），标注每种的适用场景。

## 二、核心教学环节话术
围绕课文重点内容，设计3-5组师生对话：
- 教师引导语（含追问设计）
- 预设学生可能的回答（包含优秀回答、一般回答、偏差回答）
- 教师点评与反馈话术（针对不同层次学生的评价语）

## 三、课堂管理话术
- 小组讨论的组织引导语
- 注意力不集中时的提醒语
- 课堂节奏调控语

## 四、总结评价话术
- 课堂小结语（引导学生自主总结）
- 鼓励性评价语（10条以上，适用于不同场景）
- 课后延伸引导语

## 五、教学点评预设
- 本课亮点预设
- 可能出现的冷场及化解策略

请让话术自然亲切、富有感染力，符合中小学生心理特点。"""


def get_homework_prompt(grade, lesson, layer="基础"):
    """分层作业提示词"""
    layer_desc = {
        "基础": "面向全体学生，侧重基础知识巩固和基本能力训练",
        "提高": "面向中等及以上学生，在基础上增加理解和应用层次",
        "拓展": "面向学有余力的学生，注重综合运用和创新思维"
    }
    desc = layer_desc.get(layer, layer_desc["基础"])

    return f"""请为统编版{grade}《{lesson}》设计{layer}层次的语文作业。

层次定位：{desc}

请设计以下类型的作业：

## 一、基础知识巩固
- 字词练习（注音、书写、词语搭配、成语运用等，5-8题）
- 文学常识（2-3题）

## 二、阅读理解训练
- 课内阅读理解题（选取课文片段，设计2-3道理解题）
- 阅读方法指导（标注答题思路）

## 三、语言表达训练
- 仿写/续写/改写练习（1-2题）
- 口语表达训练（1题）

## 四、写作指导
- 片段写作训练（与本课主题相关，1题）
- 完整作文训练（如适用，含审题指导和写作提纲）

## 五、课外拓展
- 推荐阅读篇目（2-3篇，标注推荐理由）
- 实践活动建议（1个）

请确保题目设计紧扣新课标和本课教学目标，难度适中，注重语文核心素养培养。"""


def get_reading_prompt(grade, topic=""):
    """阅读练习提示词"""
    topic_text = f"，主题：{topic}" if topic else ""
    return f"""请为{grade}学生设计一套语文阅读练习{topic_text}。

请包含以下内容：

## 一、阅读材料
- 提供一篇适合{grade}学生阅读水平的短文（300-800字）
- 体裁可选：记叙文/说明文/散文/诗歌鉴赏
- 标注文章出处或"原创"

## 二、阅读理解题
设计5道阅读理解题，遵循由浅入深原则：
1. 信息提取题（基础）
2. 理解概括题（基础）
3. 品析鉴赏题（提高）
4. 拓展探究题（提高）
5. 综合运用题（拓展）

每题标注考查能力和分值。

## 三、参考答案与评分标准
- 详细答案
- 评分要点
- 常见错误提醒

请确保阅读材料思想健康、语言规范，题目设计符合新课标要求。"""


def get_writing_prompt(grade, topic=""):
    """作文指导提示词"""
    topic_text = f"，题目：{topic}" if topic else ""
    return f"""请为{grade}学生提供作文指导{topic_text}。

请包含以下内容：

## 一、作文题目设计
- 题目（如已提供则用提供的题目）
- 题目解读（审题要点）
- 写作要求

## 二、审题立意指导
- 关键词分析
- 多角度立意方向（3-4个）
- 立意选择建议

## 三、选材构思指导
- 素材选择方向
- 素材来源建议（生活、阅读、时事）
- 典型素材示例

## 四、结构布局指导
- 推荐文章结构（含图示）
- 开头技巧（2种，附示例）
- 结尾技巧（2种，附示例）
- 过渡衔接方法

## 五、写作提纲示例
提供2份不同角度的写作提纲。

## 六、范文片段展示
- 精彩开头片段
- 精彩结尾片段
- 精彩细节描写片段

## 七、常见问题与升格建议
- 该年级学生常见写作问题
- 具体升格修改建议

请确保指导专业实用，符合{grade}学生的写作水平和新课标要求。"""
